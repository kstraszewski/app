-- Storage/PDF preparation happens before the external email call. Fence that
-- side effect with a fresh lease under the same application/process locks as
-- reservation, so a delayed worker cannot send after the case advanced or
-- after another request reclaimed the generation.
CREATE FUNCTION public.renew_crm_mock_bank_dispatch_send_lease(
  p_dispatch_id uuid,
  p_request_id uuid,
  p_generation integer
) RETURNS jsonb
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $$
DECLARE
  dispatch_scope record;
  dispatch_row public.crm_mock_bank_dispatches%rowtype;
  process_stage text;
  application_reference text;
  canonical_application_reference text;
  renewal_now timestamptz := clock_timestamp();
BEGIN
  IF p_dispatch_id IS NULL
    OR p_request_id IS NULL
    OR p_generation IS NULL
    OR p_generation < 1
  THEN
    RAISE EXCEPTION 'invalid_crm_mock_bank_dispatch_lease_renewal'
      USING errcode = '22023';
  END IF;

  SELECT
    dispatch.organization_id,
    dispatch.case_id,
    dispatch.application_id,
    dispatch.kind
  INTO dispatch_scope
  FROM public.crm_mock_bank_dispatches AS dispatch
  WHERE dispatch.id = p_dispatch_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'crm_mock_bank_dispatch_lease_not_found'
      USING errcode = '42501';
  END IF;

  SELECT
    process.stage,
    submission.external_reference,
    private.crm_mock_bank_application_reference(
      application.submission_id,
      application.created_at
    )
  INTO
    process_stage,
    application_reference,
    canonical_application_reference
  FROM public.crm_case_bank_applications AS application
  JOIN public.mortgage_banks AS bank
    ON bank.id = application.bank_id
   AND bank.is_mock
  JOIN public.crm_item_submissions AS submission
    ON submission.organization_id = application.organization_id
   AND submission.case_item_id = application.case_item_id
   AND submission.id = application.submission_id
  JOIN public.crm_mortgage_application_processes AS process
    ON process.organization_id = application.organization_id
   AND process.case_id = application.case_id
   AND process.application_id = application.submission_id
  WHERE application.organization_id = dispatch_scope.organization_id
    AND application.case_id = dispatch_scope.case_id
    AND application.submission_id = dispatch_scope.application_id
  FOR UPDATE OF application, process;

  IF NOT FOUND
    OR application_reference IS DISTINCT FROM canonical_application_reference
  THEN
    RAISE EXCEPTION 'crm_mock_bank_dispatch_scope_changed'
      USING errcode = '40001';
  END IF;

  SELECT dispatch.*
  INTO dispatch_row
  FROM public.crm_mock_bank_dispatches AS dispatch
  WHERE dispatch.id = p_dispatch_id
  FOR UPDATE;

  IF NOT FOUND
    OR dispatch_row.request_id IS DISTINCT FROM p_request_id
    OR dispatch_row.generation IS DISTINCT FROM p_generation
    OR dispatch_row.status <> 'pending'
    OR dispatch_row.payload_ready_at IS NULL
  THEN
    RAISE EXCEPTION 'crm_mock_bank_dispatch_lease_not_current_or_prepared'
      USING errcode = '40001';
  END IF;

  IF dispatch_row.organization_id IS DISTINCT FROM dispatch_scope.organization_id
    OR dispatch_row.case_id IS DISTINCT FROM dispatch_scope.case_id
    OR dispatch_row.application_id IS DISTINCT FROM dispatch_scope.application_id
    OR dispatch_row.kind IS DISTINCT FROM dispatch_scope.kind
    OR (dispatch_row.kind = 'esis' AND process_stage <> 'pre_application')
    OR (dispatch_row.kind = 'credit_decision' AND process_stage <> 'under_review')
  THEN
    RAISE EXCEPTION 'crm_mock_bank_dispatch_stage_or_scope_changed'
      USING errcode = '40001';
  END IF;

  UPDATE public.crm_mock_bank_dispatches AS dispatch
  SET last_attempt_at = renewal_now,
      lease_expires_at = renewal_now + interval '5 minutes',
      updated_at = renewal_now
  WHERE dispatch.id = dispatch_row.id
    AND dispatch.request_id = p_request_id
    AND dispatch.generation = p_generation
    AND dispatch.status = 'pending'
  RETURNING * INTO dispatch_row;

  IF dispatch_row.id IS NULL THEN
    RAISE EXCEPTION 'crm_mock_bank_dispatch_lease_renewal_conflict'
      USING errcode = '40001';
  END IF;

  RETURN private.crm_mock_bank_dispatch_response(
    dispatch_row.id,
    canonical_application_reference,
    'claimed',
    true
  );
END;
$$;

