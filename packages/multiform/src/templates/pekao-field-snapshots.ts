function textAppearance(
  alignment: 'left' | 'center' | 'right',
  multiline: boolean,
  comb: boolean,
  maxLength?: number,
): PdfTextAppearance {
  return {
  kind: 'text',
  fontId: 'dm-sans-regular',
  fontSizePt: 10,
  minFontSizePt: 5,
  letterSpacingPt: 0,
  lineHeightPt: 12,
  wrap: multiline ? 'word' : 'none',
  overflow: 'shrink',
  horizontalAlign: alignment,
  verticalAlign: 'middle',
  distribution: comb && maxLength
    ? { kind: 'comb', cells: maxLength }
    : { kind: 'flow' },
  color: { space: 'rgb', red: 0, green: 0, blue: 0 },
  opacity: 1,
  paddingPt: { top: 1.5, right: 1.5, bottom: 1.5, left: 1.5 },
  }
}

const MARK_APPEARANCE: PdfMarkAppearance = {
  kind: 'mark',
  role: 'checkbox',
  glyph: 'x',
  color: { space: 'rgb', red: 0, green: 0, blue: 0 },
  opacity: 1,
  insetPt: 1.5,
  strokeWidthPt: 0.9,
  outline: {
    shape: 'square',
    color: { space: 'rgb', red: 0, green: 0, blue: 0 },
    strokeWidthPt: 0.6,
  },
}

export function pekaoAcroTarget(
  field: string,
  valueMap?: Readonly<Record<string, string>>,
): AcroFormTarget {
  const snapshot = PEKAO_FIELD_SNAPSHOTS.get(field)
  if (!snapshot) throw new Error(`Missing reviewed Pekao AcroForm snapshot: ${field}`)

  const [
    fieldType,
    page,
    x,
    y,
    width,
    height,
    alignment = 'left',
    multiline = false,
    comb = false,
    maxLength,
  ] = snapshot
  return {
    kind: 'acroform',
    field,
    fieldType,
    expectedWidgets: [{
      index: 0,
      page,
      rect: { x, y, width, height },
      ...(fieldType === 'checkbox' ? { exportValue: 'Yes' } : {}),
    }],
    ...(fieldType === 'text'
      ? {
          text: {
            alignment,
            multiline,
            comb,
            ...(maxLength !== undefined ? { maxLength } : {}),
          },
          appearance: textAppearance(alignment, multiline, comb, maxLength),
        }
      : { appearance: MARK_APPEARANCE }),
    ...(valueMap ? { valueMap } : {}),
  }
}
