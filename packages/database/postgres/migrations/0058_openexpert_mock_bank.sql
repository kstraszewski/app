CREATE FUNCTION public.commit_crm_mock_bank_dispatch_payload(
  p_dispatch_id uuid,
  p_request_id uuid,
  p_generation integer,
  p_manifest_sha256 text,
  p_manifest_size_bytes integer,
  p_archive_sha256 text,
  p_archive_size_bytes integer,
  p_payload_sha256 text
) RETURNS jsonb
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $$
DECLARE
  dispatch_row public.crm_mock_bank_dispatches%rowtype;
  application_reference text;
  committed_now timestamptz := clock_timestamp();
BEGIN
  IF p_dispatch_id IS NULL
    OR p_request_id IS NULL
    OR p_generation IS NULL
    OR p_generation < 1
    OR p_manifest_sha256 !~ '^[0-9a-f]{64}$'
    OR p_archive_sha256 !~ '^[0-9a-f]{64}$'
    OR p_payload_sha256 !~ '^[0-9a-f]{64}$'
    OR p_manifest_size_bytes NOT BETWEEN 1 AND 5242880
    OR p_archive_size_bytes NOT BETWEEN 1 AND 5242880
  THEN
    RAISE EXCEPTION 'invalid_crm_mock_bank_payload_commit'
      USING errcode = '22023';
  END IF;

  SELECT dispatch.*
  INTO dispatch_row
  FROM public.crm_mock_bank_dispatches AS dispatch
  WHERE dispatch.id = p_dispatch_id
  FOR UPDATE;

  IF NOT FOUND
    OR dispatch_row.request_id IS DISTINCT FROM p_request_id
    OR dispatch_row.generation IS DISTINCT FROM p_generation
  THEN
    RAISE EXCEPTION 'crm_mock_bank_dispatch_lease_not_found'
      USING errcode = '42501';
  END IF;

  SELECT submission.external_reference
  INTO application_reference
  FROM public.crm_item_submissions AS submission
  WHERE submission.id = dispatch_row.application_id;

  IF dispatch_row.status <> 'pending'
    OR dispatch_row.lease_expires_at <= committed_now
  THEN
    RAISE EXCEPTION 'crm_mock_bank_dispatch_lease_expired_or_finalized'
      USING errcode = '40001';
  END IF;

  IF dispatch_row.payload_ready_at IS NOT NULL THEN
    IF dispatch_row.manifest_sha256 IS DISTINCT FROM p_manifest_sha256
      OR dispatch_row.manifest_size_bytes IS DISTINCT FROM p_manifest_size_bytes
      OR dispatch_row.archive_sha256 IS DISTINCT FROM p_archive_sha256
      OR dispatch_row.archive_size_bytes IS DISTINCT FROM p_archive_size_bytes
      OR dispatch_row.payload_sha256 IS DISTINCT FROM p_payload_sha256
    THEN
      RAISE EXCEPTION 'crm_mock_bank_payload_commit_mismatch'
        USING errcode = '23514';
    END IF;
    RETURN private.crm_mock_bank_dispatch_response(
      dispatch_row.id,
      application_reference,
      'claimed',
      true
    );
  END IF;

  UPDATE public.crm_mock_bank_dispatches AS dispatch
  SET manifest_sha256 = p_manifest_sha256,
      manifest_size_bytes = p_manifest_size_bytes,
      archive_sha256 = p_archive_sha256,
      archive_size_bytes = p_archive_size_bytes,
      payload_sha256 = p_payload_sha256,
      payload_ready_at = committed_now,
      updated_at = committed_now
  WHERE dispatch.id = dispatch_row.id
    AND dispatch.request_id = p_request_id
    AND dispatch.generation = p_generation
    AND dispatch.status = 'pending'
  RETURNING * INTO dispatch_row;

  IF dispatch_row.id IS NULL THEN
    RAISE EXCEPTION 'crm_mock_bank_payload_commit_conflict'
      USING errcode = '40001';
  END IF;

  RETURN private.crm_mock_bank_dispatch_response(
    dispatch_row.id,
    application_reference,
    'claimed',
    true
  );
END;
$$;

