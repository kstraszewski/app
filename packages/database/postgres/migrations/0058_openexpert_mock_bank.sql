CREATE FUNCTION private.expire_crm_mock_bank_payloads(
  p_limit integer
) RETURNS integer
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $$
DECLARE
  dispatch_row public.crm_mock_bank_dispatches%rowtype;
  sweep_now timestamptz := clock_timestamp();
  expired_count integer := 0;
BEGIN
  FOR dispatch_row IN
    SELECT dispatch.*
    FROM public.crm_mock_bank_dispatches AS dispatch
    WHERE dispatch.last_attempt_at <= sweep_now - interval '7 days'
      AND dispatch.error_code IS DISTINCT FROM 'payload_retention_expired'
      AND (
        dispatch.status = 'failed'
        OR (
          dispatch.status = 'pending'
          AND dispatch.lease_expires_at <= sweep_now
        )
      )
    ORDER BY dispatch.last_attempt_at, dispatch.id
    FOR UPDATE SKIP LOCKED
    LIMIT p_limit
  LOOP
    INSERT INTO public.crm_mock_bank_payload_cleanup_jobs (
      organization_id,
      dispatch_id,
      payload_id,
      generation,
      storage_bucket,
      storage_path,
      object_kind,
      object_sha256,
      available_at
    ) VALUES
      (
        dispatch_row.organization_id,
        dispatch_row.id,
        dispatch_row.payload_id,
        dispatch_row.generation,
        dispatch_row.manifest_storage_bucket,
        dispatch_row.manifest_storage_path,
        'manifest',
        dispatch_row.manifest_sha256,
        sweep_now
      ),
      (
        dispatch_row.organization_id,
        dispatch_row.id,
        dispatch_row.payload_id,
        dispatch_row.generation,
        dispatch_row.archive_storage_bucket,
        dispatch_row.archive_storage_path,
        'archive',
        dispatch_row.archive_sha256,
        sweep_now
      )
    ON CONFLICT (storage_bucket, storage_path) DO NOTHING;

    UPDATE public.crm_mock_bank_dispatches AS dispatch
    SET status = 'failed',
        manifest_sha256 = NULL,
        manifest_size_bytes = NULL,
        archive_sha256 = NULL,
        archive_size_bytes = NULL,
        payload_sha256 = NULL,
        payload_ready_at = NULL,
        provider_message_id = NULL,
        error_code = 'payload_retention_expired',
        lease_expires_at = NULL,
        sent_at = NULL,
        failed_at = sweep_now,
        updated_at = sweep_now
    WHERE dispatch.id = dispatch_row.id;

    expired_count := expired_count + 1;
  END LOOP;

  RETURN expired_count;
END;
$$;

COMMENT ON FUNCTION private.expire_crm_mock_bank_payloads(integer) IS
  'Queues and forgets private payload bytes for failed or abandoned deliveries after seven days; the next retry must start a new generation.';

REVOKE ALL ON FUNCTION private.expire_crm_mock_bank_payloads(integer)
  FROM PUBLIC, anonymous, authenticated, openexpert_service;

CREATE FUNCTION public.claim_crm_mock_bank_payload_cleanup_jobs(
  p_limit integer DEFAULT 4
) RETURNS jsonb
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $$
DECLARE
  claimed jsonb;
  claim_now timestamptz := clock_timestamp();
BEGIN
  IF p_limit IS NULL OR p_limit < 1 OR p_limit > 20 THEN
    RAISE EXCEPTION 'invalid_crm_mock_bank_cleanup_limit'
      USING errcode = '22023';
  END IF;

  PERFORM private.expire_crm_mock_bank_payloads(p_limit);

  WITH selected AS (
    SELECT job.id
    FROM public.crm_mock_bank_payload_cleanup_jobs AS job
    WHERE job.status = 'pending'
      AND job.available_at <= claim_now
      AND (job.locked_at IS NULL OR job.locked_at <= claim_now - interval '5 minutes')
    ORDER BY job.available_at, job.created_at, job.id
    FOR UPDATE SKIP LOCKED
    LIMIT p_limit
  ), updated AS (
    UPDATE public.crm_mock_bank_payload_cleanup_jobs AS job
    SET claim_token = gen_random_uuid(),
        locked_at = claim_now,
        attempts = job.attempts + 1,
        last_error = NULL,
        updated_at = claim_now
    FROM selected
    WHERE job.id = selected.id
    RETURNING job.*
  )
  SELECT coalesce(
    jsonb_agg(
      jsonb_build_object(
        'jobId', updated.id,
        'claimToken', updated.claim_token,
        'storageBucket', updated.storage_bucket,
        'storagePath', updated.storage_path,
        'objectSha256', updated.object_sha256,
        'attempts', updated.attempts
      ) ORDER BY updated.created_at, updated.id
    ),
    '[]'::jsonb
  )
  INTO claimed
  FROM updated;

  RETURN claimed;
END;
$$;

CREATE FUNCTION public.finalize_crm_mock_bank_payload_cleanup_job(
  p_job_id uuid,
  p_claim_token uuid,
  p_succeeded boolean,
  p_error_code text DEFAULT NULL
) RETURNS void
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $$
DECLARE
  normalized_error text := nullif(btrim(p_error_code), '');
  completed_now timestamptz := clock_timestamp();
BEGIN
  IF p_job_id IS NULL
    OR p_claim_token IS NULL
    OR p_succeeded IS NULL
    OR (p_succeeded AND normalized_error IS NOT NULL)
    OR (
      NOT p_succeeded
      AND (
        normalized_error IS NULL
        OR char_length(normalized_error) > 100
        OR normalized_error !~ '^[a-z0-9]+([._-][a-z0-9]+)*$'
      )
    )
  THEN
    RAISE EXCEPTION 'invalid_crm_mock_bank_cleanup_completion'
      USING errcode = '22023';
  END IF;

  UPDATE public.crm_mock_bank_payload_cleanup_jobs AS job
  SET status = CASE WHEN p_succeeded THEN 'completed' ELSE 'pending' END,
      claim_token = NULL,
      locked_at = NULL,
      completed_at = CASE WHEN p_succeeded THEN completed_now ELSE NULL END,
      available_at = CASE
        WHEN p_succeeded THEN job.available_at
        ELSE completed_now + make_interval(secs => least(3600, 15 * (2 ^ least(job.attempts, 8))))
      END,
      last_error = normalized_error,
      updated_at = completed_now
  WHERE job.id = p_job_id
    AND job.status = 'pending'
    AND job.claim_token = p_claim_token;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'crm_mock_bank_cleanup_claim_not_found'
      USING errcode = '42501';
  END IF;
END;
$$;

