-- Private payload cleanup is durable. A sent transition or dispatch deletion
-- creates one job per object. API actions process jobs immediately on a
-- best-effort basis, while stale locks remain reclaimable by later actions.
CREATE TABLE public.crm_mock_bank_payload_cleanup_jobs (
  id uuid DEFAULT gen_random_uuid() PRIMARY KEY,
  organization_id uuid NOT NULL,
  dispatch_id uuid NOT NULL,
  payload_id uuid NOT NULL,
  generation integer NOT NULL,
  storage_bucket text NOT NULL,
  storage_path text NOT NULL,
  object_kind text NOT NULL,
  object_sha256 text,
  status text DEFAULT 'pending'::text NOT NULL,
  attempts integer DEFAULT 0 NOT NULL,
  available_at timestamptz DEFAULT now() NOT NULL,
  claim_token uuid,
  locked_at timestamptz,
  completed_at timestamptz,
  last_error text,
  created_at timestamptz DEFAULT now() NOT NULL,
  updated_at timestamptz DEFAULT now() NOT NULL,
  CONSTRAINT crm_mock_bank_payload_cleanup_jobs_object_key
    UNIQUE (storage_bucket, storage_path),
  CONSTRAINT crm_mock_bank_payload_cleanup_jobs_bucket_check CHECK (
    storage_bucket = 'crm-mock-bank-outbox'::text
  ),
  CONSTRAINT crm_mock_bank_payload_cleanup_jobs_kind_check CHECK (
    object_kind IN ('manifest', 'archive')
  ),
  CONSTRAINT crm_mock_bank_payload_cleanup_jobs_status_check CHECK (
    status IN ('pending', 'completed')
  ),
  CONSTRAINT crm_mock_bank_payload_cleanup_jobs_generation_check CHECK (
    generation >= 1
  ),
  CONSTRAINT crm_mock_bank_payload_cleanup_jobs_attempts_check CHECK (
    attempts >= 0
  ),
  CONSTRAINT crm_mock_bank_payload_cleanup_jobs_path_check CHECK (
    storage_path LIKE organization_id::text || '/%'
    AND char_length(storage_path) <= 1024
    AND strpos(storage_path, chr(92)) = 0
    AND storage_path NOT LIKE '%//%'
    AND storage_path !~ '(^|/)[.]{1,2}(/|$)'
    AND storage_path !~ '[[:cntrl:]]'
  ),
  CONSTRAINT crm_mock_bank_payload_cleanup_jobs_hash_check CHECK (
    object_sha256 IS NULL OR object_sha256 ~ '^[0-9a-f]{64}$'
  ),
  CONSTRAINT crm_mock_bank_payload_cleanup_jobs_lock_check CHECK (
    (claim_token IS NULL AND locked_at IS NULL)
    OR (claim_token IS NOT NULL AND locked_at IS NOT NULL AND status = 'pending')
  ),
  CONSTRAINT crm_mock_bank_payload_cleanup_jobs_completion_check CHECK (
    (status = 'pending' AND completed_at IS NULL)
    OR (status = 'completed' AND completed_at IS NOT NULL AND claim_token IS NULL AND locked_at IS NULL)
  ),
  CONSTRAINT crm_mock_bank_payload_cleanup_jobs_error_check CHECK (
    last_error IS NULL OR (
      char_length(last_error) <= 100
      AND last_error ~ '^[a-z0-9]+([._-][a-z0-9]+)*$'
    )
  )
);

COMMENT ON TABLE public.crm_mock_bank_payload_cleanup_jobs IS
  'PII-free durable deletion queue for private mock-bank message manifests and encrypted archives.';

