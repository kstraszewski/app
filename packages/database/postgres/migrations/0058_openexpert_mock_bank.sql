CREATE FUNCTION private.record_crm_mock_bank_dispatch_activity()
RETURNS trigger
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $$
DECLARE
  target_case_item_id uuid;
  target_client_id uuid;
  application_reference text;
BEGIN
  SELECT
    application.case_item_id,
    coalesce(
      (
        SELECT party.client_id
        FROM public.crm_mortgage_application_parties AS party
        WHERE party.organization_id = NEW.organization_id
          AND party.case_id = NEW.case_id
          AND party.application_id = NEW.application_id
        ORDER BY (party.role = 'primary_applicant') DESC, party.created_at, party.client_id
        LIMIT 1
      ),
      crm_case.client_id
    ),
    submission.external_reference
  INTO target_case_item_id, target_client_id, application_reference
  FROM public.crm_case_bank_applications AS application
  JOIN public.crm_cases AS crm_case
    ON crm_case.organization_id = application.organization_id
   AND crm_case.id = application.case_id
  JOIN public.crm_item_submissions AS submission
    ON submission.organization_id = application.organization_id
   AND submission.case_item_id = application.case_item_id
   AND submission.id = application.submission_id
  WHERE application.organization_id = NEW.organization_id
    AND application.case_id = NEW.case_id
    AND application.submission_id = NEW.application_id;

  INSERT INTO public.crm_activities (
    organization_id,
    actor_user_id,
    client_id,
    case_id,
    case_item_id,
    submission_id,
    activity_type,
    title,
    body,
    payload,
    created_at,
    mock_bank_dispatch_id,
    mock_bank_dispatch_generation
  ) VALUES (
    NEW.organization_id,
    NEW.requested_by_user_id,
    target_client_id,
    NEW.case_id,
    target_case_item_id,
    NEW.application_id,
    CASE
      WHEN NEW.kind = 'esis' THEN 'mock_bank_esis_email_accepted'
      ELSE 'mock_bank_credit_decision_email_accepted'
    END,
    CASE
      WHEN NEW.kind = 'esis' THEN 'Dostawca poczty przyjął formularz ESIS do wysyłki'
      ELSE 'Dostawca poczty przyjął decyzję kredytową do wysyłki'
    END,
    'Dostawca przyjął wiadomość z PDF w archiwum ZIP zabezpieczonym numerem PESEL głównego wnioskodawcy. Ten wpis nie potwierdza doręczenia do skrzynki.',
    jsonb_build_object(
      'applicationId', NEW.application_id,
      'applicationNumber', application_reference,
      'documentKind', NEW.kind,
      'generation', NEW.generation,
      'providerMessageId', NEW.provider_message_id
    ),
    NEW.sent_at,
    NEW.id,
    NEW.generation
  )
  ON CONFLICT DO NOTHING;

  RETURN NEW;
END;
$$;

