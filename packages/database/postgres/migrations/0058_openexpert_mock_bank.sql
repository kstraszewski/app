-- A generation-stable delivery ledger. The encrypted archive and a strict
-- JSON manifest containing the exact provider request live in the dedicated
-- private object-store namespace. The database retains only opaque paths,
-- checksums, sizes and delivery state; the PESEL password is never persisted.
CREATE TABLE public.crm_mock_bank_dispatches (
  id uuid PRIMARY KEY,
  organization_id uuid NOT NULL,
  case_id uuid NOT NULL,
  application_id uuid NOT NULL,
  kind text NOT NULL,
  status text DEFAULT 'pending'::text NOT NULL,
  generation integer DEFAULT 1 NOT NULL,
  generation_started_at timestamptz NOT NULL,
  attempts integer DEFAULT 1 NOT NULL,
  request_id uuid NOT NULL,
  requested_by_user_id uuid,
  recipient_connection_id uuid,
  payload_id uuid NOT NULL,
  manifest_storage_bucket text DEFAULT 'crm-mock-bank-outbox'::text NOT NULL,
  manifest_storage_path text NOT NULL,
  manifest_sha256 text,
  manifest_size_bytes integer,
  archive_storage_bucket text DEFAULT 'crm-mock-bank-outbox'::text NOT NULL,
  archive_storage_path text NOT NULL,
  archive_sha256 text,
  archive_size_bytes integer,
  payload_sha256 text,
  payload_ready_at timestamptz,
  provider_message_id text,
  error_code text,
  last_attempt_at timestamptz NOT NULL,
  lease_expires_at timestamptz,
  sent_at timestamptz,
  failed_at timestamptz,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  CONSTRAINT crm_mock_bank_dispatches_application_kind_key
    UNIQUE (application_id, kind),
  CONSTRAINT crm_mock_bank_dispatches_request_key UNIQUE (request_id),
  CONSTRAINT crm_mock_bank_dispatches_kind_check CHECK (
    kind IN ('esis', 'credit_decision')
  ),
  CONSTRAINT crm_mock_bank_dispatches_status_check CHECK (
    status IN ('pending', 'sent', 'failed')
  ),
  CONSTRAINT crm_mock_bank_dispatches_generation_check CHECK (generation >= 1),
  CONSTRAINT crm_mock_bank_dispatches_attempts_check CHECK (attempts >= 1),
  CONSTRAINT crm_mock_bank_dispatches_storage_bucket_check CHECK (
    manifest_storage_bucket = 'crm-mock-bank-outbox'::text
    AND archive_storage_bucket = 'crm-mock-bank-outbox'::text
  ),
  CONSTRAINT crm_mock_bank_dispatches_storage_path_check CHECK (
    manifest_storage_path = organization_id::text || '/' ||
      application_id::text || '/' || id::text || '/' || kind || '/generation-' ||
      generation::text || '-' || payload_id::text || '.json'
    AND archive_storage_path = organization_id::text || '/' ||
      application_id::text || '/' || id::text || '/' || kind || '/generation-' ||
      generation::text || '-' || payload_id::text || '.zip'
    AND char_length(manifest_storage_path) <= 1024
    AND char_length(archive_storage_path) <= 1024
  ),
  CONSTRAINT crm_mock_bank_dispatches_payload_state_check CHECK (
    (
      manifest_sha256 IS NULL
      AND manifest_size_bytes IS NULL
      AND archive_sha256 IS NULL
      AND archive_size_bytes IS NULL
      AND payload_sha256 IS NULL
      AND payload_ready_at IS NULL
    ) OR (
      manifest_sha256 ~ '^[0-9a-f]{64}$'
      AND manifest_size_bytes BETWEEN 1 AND 5242880
      AND archive_sha256 ~ '^[0-9a-f]{64}$'
      AND archive_size_bytes BETWEEN 1 AND 5242880
      AND payload_sha256 ~ '^[0-9a-f]{64}$'
      AND payload_ready_at IS NOT NULL
    )
  ),
  CONSTRAINT crm_mock_bank_dispatches_provider_id_check CHECK (
    provider_message_id IS NULL OR (
      provider_message_id = btrim(provider_message_id)
      AND provider_message_id <> ''
      AND char_length(provider_message_id) <= 512
      AND provider_message_id !~ '[[:cntrl:]]'
    )
  ),
  CONSTRAINT crm_mock_bank_dispatches_error_code_check CHECK (
    error_code IS NULL OR (
      char_length(error_code) <= 100
      AND error_code ~ '^[a-z0-9]+([._-][a-z0-9]+)*$'
    )
  ),
  CONSTRAINT crm_mock_bank_dispatches_state_check CHECK (
    (
      status = 'pending'
      AND lease_expires_at IS NOT NULL
      AND provider_message_id IS NULL
      AND error_code IS NULL
      AND sent_at IS NULL
      AND failed_at IS NULL
    ) OR (
      status = 'sent'
      AND lease_expires_at IS NULL
      AND provider_message_id IS NOT NULL
      AND error_code IS NULL
      AND sent_at IS NOT NULL
      AND failed_at IS NULL
      AND payload_ready_at IS NOT NULL
    ) OR (
      status = 'failed'
      AND lease_expires_at IS NULL
      AND provider_message_id IS NULL
      AND error_code IS NOT NULL
      AND sent_at IS NULL
      AND failed_at IS NOT NULL
    )
  ),
  CONSTRAINT crm_mock_bank_dispatches_timestamps_check CHECK (
    isfinite(generation_started_at)
    AND isfinite(last_attempt_at)
    AND isfinite(created_at)
    AND isfinite(updated_at)
    AND (payload_ready_at IS NULL OR isfinite(payload_ready_at))
    AND (lease_expires_at IS NULL OR isfinite(lease_expires_at))
    AND (sent_at IS NULL OR isfinite(sent_at))
    AND (failed_at IS NULL OR isfinite(failed_at))
    AND generation_started_at >= created_at
    AND updated_at >= created_at
    AND last_attempt_at >= generation_started_at
    AND (payload_ready_at IS NULL OR payload_ready_at >= generation_started_at)
    AND (lease_expires_at IS NULL OR lease_expires_at > last_attempt_at)
    AND (sent_at IS NULL OR sent_at >= last_attempt_at)
    AND (failed_at IS NULL OR failed_at >= last_attempt_at)
  ),
  CONSTRAINT crm_mock_bank_dispatches_application_fk
    FOREIGN KEY (organization_id, case_id, application_id)
    REFERENCES public.crm_case_bank_applications
      (organization_id, case_id, submission_id)
    ON DELETE CASCADE,
  CONSTRAINT crm_mock_bank_dispatches_requested_actor_fk
    FOREIGN KEY (organization_id, requested_by_user_id)
    REFERENCES public.organization_memberships (organization_id, user_id)
    ON DELETE SET NULL (requested_by_user_id),
  CONSTRAINT crm_mock_bank_dispatches_recipient_connection_fk
    FOREIGN KEY (
      organization_id,
      requested_by_user_id,
      recipient_connection_id
    )
    REFERENCES public.mail_connections (organization_id, owner_user_id, id)
    ON DELETE SET NULL (recipient_connection_id)
);

