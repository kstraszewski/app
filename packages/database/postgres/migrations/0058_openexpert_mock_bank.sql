    OR p_force_resend IS NULL
  THEN
    RAISE EXCEPTION 'invalid_crm_mock_bank_dispatch_reservation'
      USING errcode = '22023';
  END IF;

  -- Match the lifecycle lock order and validate the authoritative stage under
  -- the same locks that protect a new delivery claim.
  SELECT
    membership.role,
    crm_case.owner_user_id,
    item.owner_user_id,
    submission.external_reference,
    private.crm_mock_bank_application_reference(
      application.submission_id,
      application.created_at
    ),
    process.stage
  INTO
    membership_role,
    case_owner_user_id,
    item_owner_user_id,
    application_reference,
    canonical_application_reference,
    process_stage
  FROM public.crm_case_bank_applications AS application
  JOIN public.mortgage_banks AS bank
    ON bank.id = application.bank_id
   AND bank.is_mock
  JOIN public.crm_cases AS crm_case
    ON crm_case.organization_id = application.organization_id
   AND crm_case.id = application.case_id
  JOIN public.crm_case_items AS item
    ON item.organization_id = application.organization_id
   AND item.case_id = application.case_id
   AND item.id = application.case_item_id
  JOIN public.crm_item_submissions AS submission
    ON submission.organization_id = application.organization_id
   AND submission.case_item_id = application.case_item_id
   AND submission.id = application.submission_id
  JOIN public.crm_mortgage_application_processes AS process
    ON process.organization_id = application.organization_id
   AND process.case_id = application.case_id
   AND process.application_id = application.submission_id
  JOIN public.organization_memberships AS membership
    ON membership.organization_id = application.organization_id
   AND membership.user_id = p_requested_by_user_id
  WHERE application.organization_id = p_organization_id
    AND application.case_id = p_case_id
    AND application.submission_id = p_application_id
  FOR UPDATE OF application, process;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'crm_mock_bank_application_scope_or_membership_not_found'
      USING errcode = '42501';
  END IF;

  IF membership_role <> 'admin'
    AND case_owner_user_id IS DISTINCT FROM p_requested_by_user_id
    AND item_owner_user_id IS DISTINCT FROM p_requested_by_user_id
  THEN
    RAISE EXCEPTION 'mortgage_case_manager_permission_required'
      USING errcode = '42501';
  END IF;

  IF application_reference IS DISTINCT FROM canonical_application_reference
    OR canonical_application_reference !~ '^OEB-[0-9]{8}-[0-9]{6}$'
  THEN
    RAISE EXCEPTION 'crm_mock_bank_application_reference_invalid_or_tampered'
      USING errcode = '55000';
  END IF;
  application_reference := canonical_application_reference;

  IF NOT EXISTS (
    SELECT 1
    FROM public.mail_connections AS connection
    WHERE connection.organization_id = p_organization_id
      AND connection.owner_user_id = p_requested_by_user_id
      AND connection.id = p_recipient_connection_id
      AND connection.status = 'active'
  ) THEN
    RAISE EXCEPTION 'crm_mock_bank_recipient_connection_not_active'
      USING errcode = '42501';
  END IF;

  SELECT dispatch.*
  INTO dispatch_row
  FROM public.crm_mock_bank_dispatches AS dispatch
  WHERE dispatch.application_id = p_application_id
    AND dispatch.kind = p_kind
  FOR UPDATE;

  IF FOUND AND dispatch_row.status = 'sent' AND NOT p_force_resend THEN
    RETURN private.crm_mock_bank_dispatch_response(
      dispatch_row.id,
      application_reference,
      'sent',
      false
    );
  END IF;

  IF FOUND
    AND dispatch_row.status = 'pending'
    AND dispatch_row.lease_expires_at > lease_now
  THEN
    RETURN private.crm_mock_bank_dispatch_response(
      dispatch_row.id,
      application_reference,
      'in_progress',
      false
    );
  END IF;

  IF (p_kind = 'esis' AND process_stage <> 'pre_application')
    OR (p_kind = 'credit_decision' AND process_stage <> 'under_review')
  THEN
    RAISE EXCEPTION 'crm_mock_bank_dispatch_stage_mismatch'
      USING errcode = '23514';
  END IF;

  IF NOT FOUND THEN
    IF p_force_resend THEN
      RAISE EXCEPTION 'crm_mock_bank_force_resend_requires_sent_generation'
        USING errcode = '22023';
    END IF;
    next_dispatch_id := gen_random_uuid();
    next_payload_id := gen_random_uuid();
    INSERT INTO public.crm_mock_bank_dispatches (
      id,
      organization_id,
      case_id,
      application_id,
      kind,
      status,
      generation,
      generation_started_at,
      attempts,
      request_id,
      requested_by_user_id,
      recipient_connection_id,
      payload_id,
      manifest_storage_path,
      archive_storage_path,
      last_attempt_at,
      lease_expires_at,
      created_at,
      updated_at
    ) VALUES (
      next_dispatch_id,
      p_organization_id,
      p_case_id,
      p_application_id,
      p_kind,
      'pending',
      1,
      lease_now,
      1,
      p_request_id,
      p_requested_by_user_id,
      p_recipient_connection_id,
      next_payload_id,
      p_organization_id::text || '/' || p_application_id::text || '/' ||
        next_dispatch_id::text || '/' || p_kind || '/generation-1-' ||
        next_payload_id::text || '.json',
      p_organization_id::text || '/' || p_application_id::text || '/' ||
        next_dispatch_id::text || '/' || p_kind || '/generation-1-' ||
        next_payload_id::text || '.zip',
      lease_now,
      lease_now + interval '5 minutes',
      lease_now,
      lease_now
    )
    RETURNING * INTO dispatch_row;

    RETURN private.crm_mock_bank_dispatch_response(
      dispatch_row.id,
      application_reference,
      'claimed',
      true
    );
  END IF;

  IF dispatch_row.request_id = p_request_id THEN
    RAISE EXCEPTION 'crm_mock_bank_dispatch_new_request_required'
      USING errcode = '22023';
  END IF;

  IF dispatch_row.status = 'sent' THEN
    IF dispatch_row.sent_at > lease_now - interval '60 seconds' THEN
      RAISE EXCEPTION 'crm_mock_bank_force_resend_cooldown'
        USING errcode = '55000';
    END IF;
    -- An explicit resend is a new business generation with a new payload and
    -- Resend idempotency identity. It may deliberately bind another mailbox.
    next_generation := dispatch_row.generation + 1;
    next_payload_id := gen_random_uuid();
    UPDATE public.crm_mock_bank_dispatches AS dispatch
    SET status = 'pending',
        generation = next_generation,
        generation_started_at = lease_now,
        attempts = 1,
        request_id = p_request_id,
        requested_by_user_id = p_requested_by_user_id,
        recipient_connection_id = p_recipient_connection_id,
        payload_id = next_payload_id,
        manifest_storage_path = p_organization_id::text || '/' ||
          p_application_id::text || '/' || dispatch.id::text || '/' || p_kind ||
          '/generation-' || next_generation::text || '-' || next_payload_id::text || '.json',
        manifest_sha256 = NULL,
        manifest_size_bytes = NULL,
        archive_storage_path = p_organization_id::text || '/' ||
          p_application_id::text || '/' || dispatch.id::text || '/' || p_kind ||
          '/generation-' || next_generation::text || '-' || next_payload_id::text || '.zip',
        archive_sha256 = NULL,
        archive_size_bytes = NULL,
        payload_sha256 = NULL,
        payload_ready_at = NULL,
        provider_message_id = NULL,
        error_code = NULL,
        last_attempt_at = lease_now,
        lease_expires_at = lease_now + interval '5 minutes',
        sent_at = NULL,
        failed_at = NULL,
        updated_at = lease_now
    WHERE dispatch.id = dispatch_row.id
    RETURNING * INTO dispatch_row;
  ELSIF dispatch_row.status = 'failed'
    AND dispatch_row.error_code = 'payload_retention_expired'
  THEN
    IF p_force_resend THEN
      RAISE EXCEPTION 'crm_mock_bank_force_resend_requires_sent_generation'
        USING errcode = '22023';
    END IF;
    -- The prior encrypted bytes were durably deleted after the retention
    -- window. Restart with a fresh business generation and idempotency key;
    -- never recreate different bytes under the expired generation.
    next_generation := dispatch_row.generation + 1;
    next_payload_id := gen_random_uuid();
    UPDATE public.crm_mock_bank_dispatches AS dispatch
    SET status = 'pending',
        generation = next_generation,
        generation_started_at = lease_now,
        attempts = 1,
        request_id = p_request_id,
        requested_by_user_id = p_requested_by_user_id,
        recipient_connection_id = p_recipient_connection_id,
        payload_id = next_payload_id,
        manifest_storage_path = p_organization_id::text || '/' ||
          p_application_id::text || '/' || dispatch.id::text || '/' || p_kind ||
          '/generation-' || next_generation::text || '-' || next_payload_id::text || '.json',
        manifest_sha256 = NULL,
        manifest_size_bytes = NULL,
        archive_storage_path = p_organization_id::text || '/' ||
          p_application_id::text || '/' || dispatch.id::text || '/' || p_kind ||
          '/generation-' || next_generation::text || '-' || next_payload_id::text || '.zip',
        archive_sha256 = NULL,
        archive_size_bytes = NULL,
        payload_sha256 = NULL,
        payload_ready_at = NULL,
        provider_message_id = NULL,
        error_code = NULL,
        last_attempt_at = lease_now,
        lease_expires_at = lease_now + interval '5 minutes',
        sent_at = NULL,
        failed_at = NULL,
        updated_at = lease_now
    WHERE dispatch.id = dispatch_row.id
    RETURNING * INTO dispatch_row;
  ELSE
    IF p_force_resend THEN
      RAISE EXCEPTION 'crm_mock_bank_force_resend_requires_sent_generation'
        USING errcode = '22023';
    END IF;
    IF dispatch_row.recipient_connection_id IS NULL
      OR dispatch_row.recipient_connection_id IS DISTINCT FROM p_recipient_connection_id
      OR dispatch_row.requested_by_user_id IS DISTINCT FROM p_requested_by_user_id
    THEN
      RAISE EXCEPTION 'crm_mock_bank_dispatch_recipient_binding_mismatch'
        USING errcode = '23514';
    END IF;

    -- Retry the same generation. The payload identity, object paths, issue
    -- date and recipient binding remain immutable.
    UPDATE public.crm_mock_bank_dispatches AS dispatch
    SET status = 'pending',
        attempts = dispatch.attempts + 1,
        request_id = p_request_id,
        provider_message_id = NULL,
        error_code = NULL,
        last_attempt_at = lease_now,
        lease_expires_at = lease_now + interval '5 minutes',
        sent_at = NULL,
        failed_at = NULL,
        updated_at = lease_now
    WHERE dispatch.id = dispatch_row.id
    RETURNING * INTO dispatch_row;
  END IF;

  RETURN private.crm_mock_bank_dispatch_response(
    dispatch_row.id,
    application_reference,
    'claimed',
    true
  );
END;
$$;

