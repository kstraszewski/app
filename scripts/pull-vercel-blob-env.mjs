import { randomUUID } from 'node:crypto'
import {
  chmodSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const scriptDirectory = dirname(fileURLToPath(import.meta.url))
const repositoryRoot = resolve(scriptDirectory, '..')
const outputPath = resolve(repositoryRoot, '.env.blob.local')
const temporaryDirectory = join(
  tmpdir(),
  `openexpert-vercel-blob-${randomUUID()}`,
)
const pulledEnvironmentPath = join(temporaryDirectory, 'development.env')
const blobKeys = [
  'VERCEL_OIDC_TOKEN',
  'NUXT_VERCEL_BLOB_PUBLIC_TOKEN',
  'NUXT_VERCEL_BLOB_PUBLIC_STORE_ID',
  'NUXT_VERCEL_BLOB_PUBLIC_BASE_URL',
  'NUXT_VERCEL_BLOB_PRIVATE_TOKEN',
  'NUXT_VERCEL_BLOB_PRIVATE_STORE_ID',
]

function parseEnvFile(content) {
  const values = {}
  for (const rawLine of content.split(/\r?\n/u)) {
    const line = rawLine.trim()
    if (!line || line.startsWith('#')) continue

    const separator = line.indexOf('=')
    if (separator < 1) continue
    const key = line.slice(0, separator).trim()
    let value = line.slice(separator + 1).trim()
    if (value.startsWith('"') && value.endsWith('"')) {
      try {
        value = JSON.parse(value)
      }
      catch {
        value = value.slice(1, -1)
      }
    }
    else if (value.startsWith('\'') && value.endsWith('\'')) {
      value = value.slice(1, -1)
    }
    values[key] = value
  }
  return values
}

function hasValue(values, key) {
  return typeof values[key] === 'string' && values[key].trim() !== ''
}

function assertBlobConfiguration(values) {
  const hasPublicAuth = hasValue(values, 'NUXT_VERCEL_BLOB_PUBLIC_TOKEN')
    || hasValue(values, 'NUXT_VERCEL_BLOB_PUBLIC_STORE_ID')
  const hasPrivateAuth = hasValue(values, 'NUXT_VERCEL_BLOB_PRIVATE_TOKEN')
    || hasValue(values, 'NUXT_VERCEL_BLOB_PRIVATE_STORE_ID')
  const usesOidc = !hasValue(values, 'NUXT_VERCEL_BLOB_PUBLIC_TOKEN')
    || !hasValue(values, 'NUXT_VERCEL_BLOB_PRIVATE_TOKEN')

  if (!hasPublicAuth || !hasPrivateAuth) {
    throw new Error(
      'The linked Vercel Development environment is missing a public or private Blob store.',
    )
  }
  if (usesOidc && !hasValue(values, 'VERCEL_OIDC_TOKEN')) {
    throw new Error(
      'The linked Vercel Development environment did not provide VERCEL_OIDC_TOKEN.',
    )
  }
}

mkdirSync(temporaryDirectory, { recursive: false, mode: 0o700 })
try {
  const command = process.platform === 'win32' ? 'pnpm.cmd' : 'pnpm'
  const result = spawnSync(command, [
    'dlx',
    'vercel@59.1.4',
    'env',
    'pull',
    pulledEnvironmentPath,
    '--environment=development',
    '--yes',
  ], {
    cwd: repositoryRoot,
    stdio: 'inherit',
  })
  if (result.error) throw result.error
  if (result.status !== 0) {
    throw new Error(`Vercel env pull exited with status ${result.status}.`)
  }

  const pulledValues = parseEnvFile(readFileSync(pulledEnvironmentPath, 'utf8'))
  assertBlobConfiguration(pulledValues)
  const selectedEntries = blobKeys
    .filter(key => hasValue(pulledValues, key))
    .map(key => `${key}=${JSON.stringify(pulledValues[key])}`)
  const content = [
    '# Generated by pnpm storage:env:pull. Do not commit.',
    ...selectedEntries,
    '',
  ].join('\n')

  writeFileSync(outputPath, content, { encoding: 'utf8', mode: 0o600 })
  chmodSync(outputPath, 0o600)
  console.log(`Saved ${selectedEntries.length} Blob settings to .env.blob.local.`)
}
finally {
  rmSync(temporaryDirectory, { recursive: true, force: true })
}
