-- Applications created from a synthetic institution receive a stable,
-- human-readable bank reference. The six-digit suffix is the first uint32 of
-- SHA-256(lowercase UUID), interpreted big-endian and reduced modulo 1,000,000.
-- The document generator uses the same algorithm, so the PDF, attachment and
-- CRM application always carry the same number without storing another secret.
CREATE FUNCTION private.crm_mock_bank_application_reference(
  p_application_id uuid,
  p_created_at timestamptz
) RETURNS text
  LANGUAGE sql
  STABLE
  STRICT
  SET search_path TO ''
  AS $$
    WITH digest_bytes AS (
      SELECT extensions.digest(
        convert_to(lower(p_application_id::text), 'UTF8'),
        'sha256'
      ) AS value
    )
    SELECT format(
      'OEB-%s-%s',
      to_char(
        (p_created_at AT TIME ZONE 'Europe/Warsaw')::date,
        'YYYYMMDD'
      ),
      lpad((
        (
          get_byte(value, 0)::bigint * 16777216
          + get_byte(value, 1)::bigint * 65536
          + get_byte(value, 2)::bigint * 256
          + get_byte(value, 3)::bigint
        ) % 1000000
      )::text, 6, '0')
    )
    FROM digest_bytes;
  $$;

COMMENT ON FUNCTION private.crm_mock_bank_application_reference(
  uuid, timestamptz
) IS
  'Builds OEB-YYYYMMDD-###### from Warsaw creation date and the first big-endian uint32 of SHA-256(lowercase application UUID), modulo one million.';

REVOKE ALL ON FUNCTION private.crm_mock_bank_application_reference(
  uuid, timestamptz
) FROM PUBLIC, anonymous, authenticated, openexpert_service;

CREATE FUNCTION private.assign_crm_mock_bank_application_reference()
RETURNS trigger
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM public.mortgage_banks AS bank
    WHERE bank.id = NEW.bank_id
      AND bank.is_mock
  ) THEN
    UPDATE public.crm_item_submissions AS submission
    SET external_reference = private.crm_mock_bank_application_reference(
      NEW.submission_id,
      NEW.created_at
    )
    WHERE submission.organization_id = NEW.organization_id
      AND submission.case_item_id = NEW.case_item_id
      AND submission.id = NEW.submission_id
      AND submission.external_reference IS DISTINCT FROM
        private.crm_mock_bank_application_reference(
          NEW.submission_id,
          NEW.created_at
        );
  END IF;

  RETURN NEW;
END;
$$;

COMMENT ON FUNCTION private.assign_crm_mock_bank_application_reference() IS
  'Assigns a stable OEB date/UUID reference to newly created applications for any explicitly marked mock institution.';

