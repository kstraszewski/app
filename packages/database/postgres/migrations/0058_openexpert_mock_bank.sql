CREATE FUNCTION private.enqueue_crm_mock_bank_payload_cleanup()
RETURNS trigger
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $$
BEGIN
  IF TG_OP = 'UPDATE'
    AND NOT (NEW.status = 'sent' AND OLD.status IS DISTINCT FROM 'sent')
  THEN
    RETURN NEW;
  END IF;

  INSERT INTO public.crm_mock_bank_payload_cleanup_jobs (
    organization_id,
    dispatch_id,
    payload_id,
    generation,
    storage_bucket,
    storage_path,
    object_kind,
    object_sha256,
    available_at
  ) VALUES
    (
      OLD.organization_id,
      OLD.id,
      OLD.payload_id,
      OLD.generation,
      OLD.manifest_storage_bucket,
      OLD.manifest_storage_path,
      'manifest',
      OLD.manifest_sha256,
      clock_timestamp()
    ),
    (
      OLD.organization_id,
      OLD.id,
      OLD.payload_id,
      OLD.generation,
      OLD.archive_storage_bucket,
      OLD.archive_storage_path,
      'archive',
      OLD.archive_sha256,
      clock_timestamp()
    )
  ON CONFLICT (storage_bucket, storage_path) DO NOTHING;

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$;

