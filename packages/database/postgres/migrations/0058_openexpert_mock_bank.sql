CREATE FUNCTION public.finalize_crm_mock_bank_dispatch(
  p_dispatch_id uuid,
  p_request_id uuid,
  p_status text,
  p_provider_message_id text DEFAULT NULL,
  p_error_code text DEFAULT NULL
) RETURNS jsonb
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $$
DECLARE
  dispatch_row public.crm_mock_bank_dispatches%rowtype;
  application_reference text;
  normalized_provider_message_id text := nullif(btrim(p_provider_message_id), '');
  normalized_error_code text := nullif(btrim(p_error_code), '');
  completed_now timestamptz := clock_timestamp();
BEGIN
  IF p_dispatch_id IS NULL
    OR p_request_id IS NULL
    OR p_status IS NULL
    OR p_status NOT IN ('sent', 'failed')
    OR (
      p_status = 'sent'
      AND (
        normalized_provider_message_id IS NULL
        OR char_length(normalized_provider_message_id) > 512
        OR normalized_provider_message_id ~ '[[:cntrl:]]'
        OR normalized_error_code IS NOT NULL
      )
    )
    OR (
      p_status = 'failed'
      AND (
        normalized_provider_message_id IS NOT NULL
        OR normalized_error_code IS NULL
        OR char_length(normalized_error_code) > 100
        OR normalized_error_code !~ '^[a-z0-9]+([._-][a-z0-9]+)*$'
      )
    )
  THEN
    RAISE EXCEPTION 'invalid_crm_mock_bank_dispatch_completion'
      USING errcode = '22023';
  END IF;

  SELECT dispatch.*
  INTO dispatch_row
  FROM public.crm_mock_bank_dispatches AS dispatch
  WHERE dispatch.id = p_dispatch_id
  FOR UPDATE;

  IF NOT FOUND OR dispatch_row.request_id IS DISTINCT FROM p_request_id THEN
    RAISE EXCEPTION 'crm_mock_bank_dispatch_lease_not_found'
      USING errcode = '42501';
  END IF;

  SELECT submission.external_reference
  INTO application_reference
  FROM public.crm_item_submissions AS submission
  WHERE submission.id = dispatch_row.application_id;

  IF dispatch_row.status = p_status THEN
    IF (
      p_status = 'sent'
      AND dispatch_row.provider_message_id IS DISTINCT FROM
        normalized_provider_message_id
    ) OR (
      p_status = 'failed'
      AND dispatch_row.error_code IS DISTINCT FROM normalized_error_code
    ) THEN
      RAISE EXCEPTION 'crm_mock_bank_dispatch_completion_mismatch'
        USING errcode = '23514';
    END IF;

    RETURN private.crm_mock_bank_dispatch_response(
      dispatch_row.id,
      application_reference,
      dispatch_row.status,
      false
    );
  END IF;

  IF dispatch_row.status <> 'pending'
    OR dispatch_row.lease_expires_at <= completed_now
    OR (p_status = 'sent' AND dispatch_row.payload_ready_at IS NULL)
  THEN
    RAISE EXCEPTION 'crm_mock_bank_dispatch_lease_expired_unprepared_or_finalized'
      USING errcode = '40001';
  END IF;

  UPDATE public.crm_mock_bank_dispatches AS dispatch
  SET status = p_status,
      provider_message_id = CASE
        WHEN p_status = 'sent' THEN normalized_provider_message_id
        ELSE NULL
      END,
      error_code = CASE
        WHEN p_status = 'failed' THEN normalized_error_code
        ELSE NULL
      END,
      lease_expires_at = NULL,
      sent_at = CASE WHEN p_status = 'sent' THEN completed_now ELSE NULL END,
      failed_at = CASE WHEN p_status = 'failed' THEN completed_now ELSE NULL END,
      updated_at = completed_now
  WHERE dispatch.id = dispatch_row.id
    AND dispatch.request_id = p_request_id
    AND dispatch.status = 'pending'
  RETURNING * INTO dispatch_row;

  IF dispatch_row.id IS NULL THEN
    RAISE EXCEPTION 'crm_mock_bank_dispatch_completion_conflict'
      USING errcode = '40001';
  END IF;

  RETURN private.crm_mock_bank_dispatch_response(
    dispatch_row.id,
    application_reference,
    dispatch_row.status,
    false
  );
END;
$$;

