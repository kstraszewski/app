-- A provider call happens outside the database transaction that owns the
-- reservation. Keep the referenced application and its authoritative stage
-- stable for the short lease so a concurrent delete/transition cannot erase
-- the ledger after the provider has accepted the message.
CREATE FUNCTION private.guard_crm_mock_bank_application_delete_during_delivery()
RETURNS trigger
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM public.crm_mock_bank_dispatches AS dispatch
    WHERE dispatch.organization_id = OLD.organization_id
      AND dispatch.case_id = OLD.case_id
      AND dispatch.application_id = OLD.submission_id
      AND dispatch.status = 'pending'
      AND dispatch.lease_expires_at > clock_timestamp()
  ) THEN
    RAISE EXCEPTION 'crm_mock_bank_delivery_lease_active'
      USING errcode = '55000';
  END IF;
  RETURN OLD;
END;
$$;

REVOKE ALL ON FUNCTION private.guard_crm_mock_bank_application_delete_during_delivery()
  FROM PUBLIC, anonymous, authenticated, openexpert_service;

CREATE TRIGGER crm_case_bank_applications_guard_mock_delivery_delete
  BEFORE DELETE ON public.crm_case_bank_applications
  FOR EACH ROW
  EXECUTE FUNCTION private.guard_crm_mock_bank_application_delete_during_delivery();

CREATE FUNCTION private.guard_crm_mock_bank_process_transition_during_delivery()
RETURNS trigger
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $$
BEGIN
  IF NEW.stage IS DISTINCT FROM OLD.stage
    AND EXISTS (
      SELECT 1
      FROM public.crm_mock_bank_dispatches AS dispatch
      WHERE dispatch.organization_id = OLD.organization_id
        AND dispatch.case_id = OLD.case_id
        AND dispatch.application_id = OLD.application_id
        AND dispatch.status = 'pending'
        AND dispatch.lease_expires_at > clock_timestamp()
    )
  THEN
    RAISE EXCEPTION 'crm_mock_bank_delivery_lease_active'
      USING errcode = '55000';
  END IF;
  RETURN NEW;
END;
$$;

REVOKE ALL ON FUNCTION private.guard_crm_mock_bank_process_transition_during_delivery()
  FROM PUBLIC, anonymous, authenticated, openexpert_service;

CREATE TRIGGER crm_mortgage_processes_guard_mock_delivery_transition
